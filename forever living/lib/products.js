export function getProduct(ref) {
  return products.find((p) => String(p.ref) === String(ref));
}

export function getCategories(locale) {
  const key = locale === 'ar' ? 'categoryAr' : 'categoryFr';
  return [...new Set(products.map((p) => p[key]))];
}

export function getNeedGroup(id) {
  return needGroups.find((g) => g.id === id);
}

export function getRelatedProducts(product, limit = 4) {
  if (!product) return [];
  const tags = product.needTags || [];
  return products
    .filter((p) => p.ref !== product.ref)
    .map((p) => ({
      product: p,
      score: (p.needTags || []).filter((tag) => tags.includes(tag)).length +
        (p.categoryAr === product.categoryAr ? 1 : 0)
    }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.product);
}
